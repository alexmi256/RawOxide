#!/usr/bin/env python3
"""Copy the reference profile registry into `assets/` and regenerate the
embedded Rust table.

Usage:
    python3 scripts/embed_profiles.py [--python-root RawHide]

The registry is static data (one `profile.json` per camera plus the three
Adobe lookup blobs), so the generated table is committed. Re-run this after
the registry changes and review the diff like source.
"""

from __future__ import annotations

import argparse
import os
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets" / "profiles"
GENERATED = ROOT / "crates" / "rawoxide-core" / "src" / "profiles_generated.rs"


def copy_registry(source: Path) -> None:
    if ASSETS.exists():
        shutil.rmtree(ASSETS)
    ASSETS.mkdir(parents=True)
    for path in sorted(source.rglob("*")):
        if path.is_dir() or "__pycache__" in path.parts:
            continue
        if path.name == "profile.json" or path.suffix == ".bin":
            target = ASSETS / path.relative_to(source)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, target)


def generate() -> None:
    profiles: list[tuple[str, str]] = []
    for path in sorted(ASSETS.rglob("profile.json")):
        relative = path.relative_to(ASSETS)
        data = json.loads(path.read_text())
        slug = data.get("slug", relative.parent.name)
        profiles.append((slug, str(relative)))
    assets = [str(path.relative_to(ASSETS)) for path in sorted(ASSETS.rglob("*.bin"))]

    lines = [
        "// @generated by scripts/embed_profiles.py; do not edit.",
        "",
        "#[allow(clippy::all)]",
        "pub(super) static PROFILE_FILES: &[(&str, &str)] = &[",
    ]
    lines.extend(
        f'    ({json.dumps(slug)}, include_str!("../../../assets/profiles/{relative}")),'
        for slug, relative in profiles
    )
    lines.extend(["", "];", "", "#[allow(clippy::all)]", "pub(super) static ASSET_FILES: &[(&str, &[u8])] = &["])
    lines.extend(
        f'    ({json.dumps(relative)}, include_bytes!("../../../assets/profiles/{relative}")),'
        for relative in assets
    )
    lines.extend(["];", ""])
    GENERATED.write_text("\n".join(lines))
    print(f"embedded {len(profiles)} profiles and {len(assets)} assets")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--python-root", type=Path, default=Path(os.environ.get("RAWHIDE_ORACLE", ROOT / "RawHide")))
    args = parser.parse_args()
    source = args.python_root / "stegodng" / "profiles"
    if not source.is_dir():
        parser.error(f"no profile registry at {source}")
    copy_registry(source)
    generate()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
